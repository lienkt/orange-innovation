    def _citation_line(self, signal_ids: list[str] | None, topic: dict[str, Any]) -> list[Any]:
        if not signal_ids:
            return []
        by_id = {s["id"]: s for s in topic.get("signals") or []}
        parts = []
        for signal_id in signal_ids[:6]:
            signal = by_id.get(signal_id)
            parts.append(
                f"{signal_id} {signal['publisher'][:22]} {signal['published_at']}" if signal else signal_id
            )
        return [Paragraph("Sources: " + _text("; ".join(parts)), self.styles["cite"])]


