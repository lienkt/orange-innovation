"""Sales and presales brief as a PDF (FR-18).

FR-18 was listed in the README as deliberately not built, with the note that
"the read API exposes everything an exporter needs". This is that exporter.

The brief is assembled, not written. Three kinds of content meet on the page and
they are kept visibly distinct, because a reader has to know which is which:

  computed    scores, market sizes, competitive intensity, portfolio distance.
              Produced by `scoring`, `sizing` and `competition`, reproducible
              from stored inputs (DR-05), never generated by a model.
  curated     named Orange assets, references, certifications, competitors —
              from the business graph and the competitor register (DR-11).
  written     the narrative sections and the solution diagram, generated under
              the §4.4.4 defences and stripped where they failed them.

Every figure on the page therefore has a provenance, and the last page says so:
the weight set that produced the scores, the sizing version that produced the
money, the competitor register version, and the prompt and model that wrote the
prose (DR-10, NFR-02). A brief that cannot be traced is a brochure.

reportlab is used rather than an HTML-to-PDF pipeline: it has no browser
dependency, which matters for a sovereign deployment (NFR-05), and the solution
diagram is drawn with exact geometry rather than hoped-for CSS.
"""

