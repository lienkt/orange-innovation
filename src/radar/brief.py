class BriefBuilder:
    """Assembles one opportunity brief and renders it to a PDF file."""

    def __init__(self, cfg: Config, db: Database, output_dir: Path | None = None):
        self.cfg = cfg
        self.db = db
        self.read = ReadModel(cfg, db)
        self.styles = _styles()
        self.output_dir = Path(
            output_dir or os.getenv("RADAR_BRIEF_DIR")
            or (Path(cfg.db_path).parent / "briefs")
        )

    # ------------------------------------------------------------------

    def build(self, topic_id: str) -> dict[str, Any]:
        topic = self.read.topic(topic_id)
        if topic is None:
            raise KeyError(f"No such topic: {topic_id}")
        description = description_for_topic(self.db, topic_id)
        competition = competition_for_topic(self.db, topic_id)
        sizes = sizes_for_topic(self.db, topic_id)
        analysis = analysis_for_topic(self.db, topic_id)

        self.output_dir.mkdir(parents=True, exist_ok=True)
        filename = f"{topic_id}-opportunity-brief.pdf"
        path = self.output_dir / filename
        story = self._story(topic, description, competition, sizes, analysis)
        self._render(path, story, topic)

        payload = path.read_bytes()
        digest = hashlib.sha256(payload).hexdigest()
        now = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")
        with self.db.cursor() as cur:
            cur.execute(
                """INSERT INTO topic_briefs
                       (opportunity_id, generated_at, topic_version, path, filename, bytes,
                        content_hash, description_at, market_size_at, weight_set, sizing_version,
                        prompt_version, model_version, pipeline_version, brief_schema)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                   ON CONFLICT(opportunity_id) DO UPDATE SET
                       generated_at=excluded.generated_at, topic_version=excluded.topic_version,
                       path=excluded.path, filename=excluded.filename, bytes=excluded.bytes,
                       content_hash=excluded.content_hash, description_at=excluded.description_at,
                       market_size_at=excluded.market_size_at, weight_set=excluded.weight_set,
                       sizing_version=excluded.sizing_version, prompt_version=excluded.prompt_version,
                       model_version=excluded.model_version, pipeline_version=excluded.pipeline_version,
                       brief_schema=excluded.brief_schema""",
                (topic_id, now, topic["version"], str(path), filename, len(payload), digest,
                 (description or {}).get("generated_at"),
                 sizes[0]["computed_at"] if sizes else None,
                 topic.get("provenance", {}).get("weight_set") or self.cfg.weight_set,
                 sizes[0]["sizing_version"] if sizes else self.cfg.sizing_version,
                 (description or {}).get("provenance", {}).get("prompt_version"),
                 (description or {}).get("provenance", {}).get("model_version"),
                 self.cfg.pipeline_version, BRIEF_SCHEMA),
            )
        log.info("Brief for %s: %s (%d bytes)", topic_id, path, len(payload))
        return brief_for_topic(self.db, topic_id) or {}

    # -- rendering ---------------------------------------------------------

    def _render(self, path: Path, story: list[Any], topic: dict[str, Any]) -> None:
        doc = BaseDocTemplate(
            str(path), pagesize=A4,
            leftMargin=17 * mm, rightMargin=17 * mm, topMargin=17 * mm, bottomMargin=16 * mm,
            title=f"{topic['id']} — {topic['statement'][:90]}",
            author="Orange Business Innovation Radar",
            subject="Opportunity space brief for sales and presales",
        )
        frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="body")
        statement = topic["statement"]
        weight_set = topic.get("provenance", {}).get("weight_set") or self.cfg.weight_set

        def decorate(canvas, document):
            canvas.saveState()
            canvas.setFillColor(ORANGE)
            canvas.rect(0, A4[1] - 6, A4[0], 6, stroke=0, fill=1)
            canvas.setFont("Helvetica", 6.6)
            canvas.setFillColor(MUTED)
            canvas.drawString(17 * mm, 10 * mm,
                              f"Orange Business Innovation Radar · {topic['id']} · "
                              f"{_clip(statement, 74)}")
            canvas.drawRightString(A4[0] - 17 * mm, 10 * mm, f"page {document.page}")
            canvas.setStrokeColor(RULE)
            canvas.setLineWidth(0.4)
            canvas.line(17 * mm, 13 * mm, A4[0] - 17 * mm, 13 * mm)
            if document.page > 1:
                canvas.setFont("Helvetica", 6.6)
                canvas.drawString(17 * mm, A4[1] - 12 * mm,
                                  f"Internal — evidence-bound opportunity brief · weight set {weight_set}")
            canvas.restoreState()

        doc.addPageTemplates([PageTemplate(id="main", frames=[frame], onPage=decorate)])
        doc.build(story)

    # -- story -------------------------------------------------------------

    def _story(self, topic: dict[str, Any], description: dict[str, Any] | None,
               competition: dict[str, Any] | None, sizes: list[dict[str, Any]],
               analysis: dict[str, Any] | None = None) -> list[Any]:
        style = self.styles
        story: list[Any] = []
        story += self._cover(topic, competition, sizes)

        if description and description.get("stale"):
            story.append(Paragraph(
                "This brief was written against an earlier version of the topic. The evidence has "
                "moved since; regenerate before using it with a customer.", style["warn"]))
        if topic.get("evidence_gap_warning"):
            density = topic.get("reference_density") or {}
            story.append(Paragraph(
                f"<b>Evidence gap (SC-13).</b> Orange has "
                f"{density.get('published_story_count', 0)} published reference(s) in "
                f"{_text(topic['labels']['vertical'])}, below the threshold of "
                f"{density.get('threshold', '?')}. A customer conversation here has no proof point "
                f"behind it yet.", style["warn"]))

        sections = (description or {}).get("sections", {})
        titles = (description or {}).get("section_titles", {})

        if "summary" in sections:
            story.append(Paragraph("The opportunity", style["h2"]))
            story.append(Paragraph(_text(sections["summary"]["text"]), style["body"]))
        elif not description:
            story.append(Paragraph(
                "No generated description yet — this brief carries the computed and curated content "
                "only. Generate one from the radar to add the narrative sections.", style["warn"]))

        story += self._market_size(sizes)
        story += self._diagram(description)

        for name in ("what_is_changing", "who_buys_and_why"):
            if name in sections:
                story.append(Paragraph(titles.get(name, name), style["h2"]))
                story.append(Paragraph(_text(sections[name]["text"]), style["body"]))
                story += self._citation_line(sections[name].get("signals"), topic)

        story += self._why_hot(topic)
        story += self._delivery(topic, sections, titles)
        story += self._competition(competition, sections, titles, topic)
        story += self._competitor_analysis(analysis)
        story += self._questions_and_objections(description)
        story += self._actions(topic, sections, titles)
        story += self._evidence_appendix(topic)
        story += self._method(topic, description, competition, sizes)
        return story

    # -- blocks ------------------------------------------------------------

    def _cover(self, topic: dict[str, Any], competition: dict[str, Any] | None,
               sizes: list[dict[str, Any]]) -> list[Any]:
        style = self.styles
        labels = topic["labels"]
        best = _preferred_size(sizes)
        attractiveness = (topic.get("attractiveness") or {}).get("score")
        right_to_win = (topic.get("right_to_win") or {}).get("score")

        header = [
            Paragraph("OPPORTUNITY BRIEF · SALES AND PRESALES", style["kicker"]),
            Paragraph(_text(topic["statement"]), style["title"]),
            Paragraph(
                f"{_text(labels['vertical'])} &nbsp;×&nbsp; {_text(labels['use_case'])} "
                f"&nbsp;×&nbsp; {_text(labels['technology'])} &nbsp;·&nbsp; {topic['id']} "
                f"v{topic['version']} &nbsp;·&nbsp; refreshed {topic['last_refresh']}",
                style["small"]),
            Spacer(1, 4),
        ]

        rows = [[
            Paragraph("ATTRACTIVENESS", style["cellhead"]),
            Paragraph("RIGHT TO WIN", style["cellhead"]),
            Paragraph("COMPETITION", style["cellhead"]),
            Paragraph("SERVICEABLE MARKET", style["cellhead"]),
            Paragraph("HORIZON", style["cellhead"]),
            Paragraph("PORTFOLIO", style["cellhead"]),
        ], [
            _big(f"{attractiveness:.0f}" if attractiveness is not None else "—", "is the world moving"),
            _big(f"{right_to_win:.0f}" if right_to_win is not None else "—", "can we play, can we win"),
            _big((competition or {}).get("level_label", "—").upper(),
                 f"{(competition or {}).get('counts', {}).get('evidenced', 0)} named in the evidence",
                 colour=COMPETITION_COLOUR.get((competition or {}).get("level", "none"), INK)),
            _big(format_eur((best or {}).get("sam", {}).get("base")) if best else "—",
                 f"{(best or {}).get('confidence', '-')} evidence · per year" if best else "not sized"),
            _big((topic.get("horizon") or "—").upper(),
                 _clip((topic.get("horizon_basis") or "").replace("_", " "), 30)),
            _big(f"L{topic['portfolio_distance']}", f"{topic['signal_count']} signals"),
        ]]
        table = Table(rows, colWidths=[29 * mm] * 6, hAlign="LEFT")
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), INK),
            ("BACKGROUND", (0, 1), (-1, 1), SURFACE),
            ("BOX", (0, 0), (-1, -1), 0.4, RULE),
            ("INNERGRID", (0, 0), (-1, -1), 0.4, RULE),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        header.append(table)
        header.append(Paragraph(
            "Attractiveness and right to win are scored and displayed separately and are never "
            "combined (SC-12). Competition is a fourth quantity, not a discount on either.",
            style["small"]))
        return header

    def _market_size(self, sizes: list[dict[str, Any]]) -> list[Any]:
        style = self.styles
        story: list[Any] = [Paragraph("Market opportunity", style["h2"])]
        if not sizes:
            story.append(Paragraph(
                "No sizing could be computed for this space. The reference data covers the "
                "European business economy; a topic outside it, or one whose technology has no "
                "published adoption series, is left unsized rather than estimated (§4.3.4).",
                style["small"]))
            return story

        head = ["Method", "Total (TAM)", "Serviceable (SAM)", "Obtainable (SOM)", "Confidence"]
        rows = [[Paragraph(h, style["cellhead"]) for h in head]]
        for size in sizes:
            rows.append([
                Paragraph(_text(size["method_label"]), style["cell"]),
                Paragraph(_range(size["tam"]), style["cell"]),
                Paragraph(_range(size["sam"]), style["cell"]),
                Paragraph(_range(size["som"]), style["cell"]),
                Paragraph(_text(size["confidence"]), style["cell"]),
            ])
        table = Table(rows, colWidths=[46 * mm, 34 * mm, 34 * mm, 34 * mm, 18 * mm], hAlign="LEFT")
        table.setStyle(_table_style())
        story.append(table)
        story.append(Paragraph("All figures are annual, in EUR. Ranges compound the uncertainty of "
                               "each factor below; the base case is the middle column of each.",
                               style["small"]))

        for size in sizes:
            story.append(Paragraph(_text(size["method_label"]), style["h3"]))
            factor_rows = [[Paragraph(h, style["cellhead"])
                            for h in ("Factor", "Value", "Basis", "Source", "As of")]]
            for factor in size["factors"]:
                source = factor.get("source") or {}
                origin = " · ".join(
                    part for part in (source.get("publisher"), source.get("dataset"),
                                      source.get("indicator")) if part
                )
                factor_rows.append([
                    Paragraph(_text(factor["label"]), style["cell"]),
                    Paragraph(_text(_factor_value(factor)), style["cell"]),
                    Paragraph(_text(factor["basis"]), style["cell"]),
                    Paragraph(_text(origin or "—"), style["cell"]),
                    Paragraph(_text(str(source.get("period") or "—")), style["cell"]),
                ])
            factors = Table(factor_rows, colWidths=[42 * mm, 32 * mm, 20 * mm, 52 * mm, 20 * mm],
                            hAlign="LEFT")
            factors.setStyle(_table_style())
            story.append(factors)
            if size["caveats"]:
                story.append(Paragraph(
                    "<b>Read this before quoting the number.</b> " +
                    " ".join(_text(c) for c in size["caveats"]), style["small"]))
        return story

    def _diagram(self, description: dict[str, Any] | None) -> list[Any]:
        diagram = (description or {}).get("diagram")
        if not diagram:
            return []
        style = self.styles
        width = A4[0] - 34 * mm
        blocks: list[Any] = [
            Paragraph("The solution, in one picture", style["h2"]),
        ]
        if diagram.get("title"):
            blocks.append(Paragraph(_text(diagram["title"]), style["h3"]))
        blocks.append(SolutionDiagram(diagram, width))
        blocks.append(Spacer(1, 5))
        legend = " &nbsp;&nbsp; ".join(
            f'<font color="{_hex(_swatch(key))}">■</font> {label}'
            for key, label in PROVIDER_LABEL.items()
        )
        blocks.append(Paragraph(legend, style["small"]))
        if diagram.get("caption"):
            blocks.append(Paragraph(_text(diagram["caption"]), style["small"]))
