class SolutionDiagram(Flowable):
    """Layered solution schematic drawn from the validated diagram spec.

    The model supplies structure (layers, boxes, providers, flows); this draws
    it. Keeping the geometry here rather than in the prompt is what makes the
    picture legible every time: boxes are sized to the layer, labels wrap at a
    measured width, and arrows are computed from real box positions instead of
    being guessed by a model that cannot see its own output.
    """

    def __init__(self, diagram: dict[str, Any], width: float):
        super().__init__()
        self.diagram = diagram
        self.width = width
        self.layers = diagram.get("layers") or []
        self.flows = diagram.get("flows") or []
        self.layer_height = 24 * mm
        self.gap = 7 * mm
        self.height = len(self.layers) * self.layer_height + max(0, len(self.layers) - 1) * self.gap

    # -- geometry ----------------------------------------------------------

    def _boxes(self) -> dict[str, tuple[float, float, float, float]]:
        """Node label -> (x, y, w, h), in flowable coordinates."""
        boxes: dict[str, tuple[float, float, float, float]] = {}
        label_column = 26 * mm
        usable = self.width - label_column - 2 * mm
        for index, layer in enumerate(self.layers):
            # Layers are listed top-down; reportlab's origin is bottom-left.
            top = self.height - index * (self.layer_height + self.gap)
            nodes = layer.get("nodes") or []
            if not nodes:
                continue
            spacing = 4 * mm
            box_width = (usable - spacing * (len(nodes) - 1)) / len(nodes)
            box_height = 15 * mm
            y = top - self.layer_height + (self.layer_height - box_height) / 2
            for position, node in enumerate(nodes):
                x = label_column + position * (box_width + spacing)
                boxes[node["label"]] = (x, y, box_width, box_height)
        return boxes

    def draw(self) -> None:
        canvas = self.canv
        boxes = self._boxes()

        for index, layer in enumerate(self.layers):
            top = self.height - index * (self.layer_height + self.gap)
            canvas.setFillColor(SURFACE)
            canvas.setStrokeColor(RULE)
            canvas.setLineWidth(0.4)
            canvas.roundRect(0, top - self.layer_height, self.width, self.layer_height, 3, stroke=1, fill=1)

            canvas.setFillColor(MUTED)
            canvas.setFont("Helvetica-Bold", 6.5)
            for line_no, line in enumerate(_wrap(layer.get("label", ""), 16)[:3]):
                canvas.drawString(3 * mm, top - 8 * mm - line_no * 7, line.upper())

            for node in layer.get("nodes") or []:
                x, y, width, height = boxes[node["label"]]
                fill, text_colour, border = PROVIDER_STYLE.get(
                    node.get("provider", "third_party"), PROVIDER_STYLE["third_party"]
                )
                canvas.setFillColor(fill)
                canvas.setStrokeColor(border)
                canvas.setLineWidth(0.9)
                canvas.roundRect(x, y, width, height, 2.5, stroke=1, fill=1)

                canvas.setFillColor(text_colour)
                canvas.setFont("Helvetica-Bold", 7.2)
                # Characters that fit at 7.2pt in this box, less a small margin.
                per_line = max(8, int((width - 4 * mm) / 3.7))
                lines = _wrap(node["label"], per_line)[:3]
                start = y + height / 2 + (len(lines) - 1) * 4.4 - 2.6
                for line_no, line in enumerate(lines):
                    canvas.drawCentredString(x + width / 2, start - line_no * 8.8, line)

        self._draw_flows(boxes)

    def _draw_flows(self, boxes: dict[str, tuple[float, float, float, float]]) -> None:
        canvas = self.canv
        canvas.setLineWidth(0.8)
        for flow in self.flows:
            source = boxes.get(flow["from"])
            target = boxes.get(flow["to"])
            if not source or not target:
                continue
            sx, sy, sw, sh = source
            tx, ty, tw, th = target
            start_x, end_x = sx + sw / 2, tx + tw / 2
            if abs(sy - ty) < 1:
                continue  # same layer: an arrow would only add noise
            going_up = ty > sy
            start_y = sy + sh if going_up else sy
            end_y = ty if going_up else ty + th

            canvas.setStrokeColor(ORANGE)
            canvas.setFillColor(ORANGE)
            canvas.line(start_x, start_y, end_x, end_y)
            self._arrowhead(end_x, end_y, start_x, start_y)

            label = (flow.get("label") or "").strip()
            if label and abs(start_y - end_y) > 12:
                text = label[:24]
                canvas.setFont("Helvetica", 5.4)
                width = canvas.stringWidth(text, "Helvetica", 5.4)
                mid_x, mid_y = (start_x + end_x) / 2, (start_y + end_y) / 2
                # The arrow passes through the label, so the label gets a solid
                # backdrop rather than being drawn on top of a line.
                canvas.setFillColor(colors.white)
                canvas.rect(mid_x - width / 2 - 1.5, mid_y - 2.4, width + 3, 7, stroke=0, fill=1)
                canvas.setFillColor(MUTED)
                canvas.drawCentredString(mid_x, mid_y, text)

    def _arrowhead(self, x: float, y: float, from_x: float, from_y: float) -> None:
        import math

        angle = math.atan2(y - from_y, x - from_x)
        size = 3.2
        path = self.canv.beginPath()
        path.moveTo(x, y)
        path.lineTo(x - size * math.cos(angle - 0.4), y - size * math.sin(angle - 0.4))
        path.lineTo(x - size * math.cos(angle + 0.4), y - size * math.sin(angle + 0.4))
        path.close()
        self.canv.drawPath(path, stroke=0, fill=1)


def _wrap(text: str, per_line: int) -> list[str]:
    words, lines, current = text.split(), [], ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if len(candidate) <= per_line:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines or [text]


