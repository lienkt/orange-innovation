def _swatch(provider: str) -> colors.Color:
    """Legend colour: the box's fill, unless the fill is too pale to see."""
    fill, _, border = PROVIDER_STYLE[provider]
    red, green, blue = fill.red, fill.green, fill.blue
    return border if (red + green + blue) / 3 > 0.9 else fill


def _hex(colour: colors.Color) -> str:
    """reportlab's hexval() is '0xrrggbb'; its markup parser wants '#rrggbb'."""
    return "#" + colour.hexval()[2:]


def _table_style() -> TableStyle:
    return TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), INK),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, SURFACE]),
        ("BOX", (0, 0), (-1, -1), 0.4, RULE),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, RULE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ])


def _big(value: str, caption: str, colour: colors.Color = INK) -> Paragraph:
    return Paragraph(
        f'<font size=13 color="{_hex(colour)}"><b>{_text(value)}</b></font><br/>'
        f'<font size=6 color="#777777">{_text(caption)}</font>',
        ParagraphStyle("kpi", fontName="Helvetica", fontSize=13, leading=15),
    )


def _range(band: dict[str, float | None]) -> str:
    base = format_eur(band.get("base"))
    low, high = format_eur(band.get("low")), format_eur(band.get("high"))
    if low == high == base:
        return base
    return f"<b>{base}</b><br/><font size=6 color='#777777'>{low} – {high}</font>"


def _factor_value(factor: dict[str, Any]) -> str:
    unit = factor.get("unit", "")
    value = factor.get("value")
    if value is None:
        return "—"
    if "EUR" in unit:
        return f"{format_eur(value)} {unit.replace('EUR ', '')}"
    if unit.startswith("%"):
        return f"{value:.1f} {unit}"
    return f"{value:,.0f} {unit}"


def _text(value: Any) -> str:
    """Make a string safe for the PDF's core fonts, then for its markup parser.

    reportlab's built-in Helvetica is a WinAnsi font, so a character outside it
    — the e-macron in "Mondelez International", say — renders as a black box.
    Substituting a Unicode TTF would fix it and change the whole document's
    typography; decomposing the accent keeps the face and loses only the
    diacritic, which is the smaller loss on a sales brief. Anything that still
    will not encode is dropped rather than boxed.
    """
    text = unicodedata.normalize("NFKD", str(value or ""))
    text = "".join(c for c in text if not unicodedata.combining(c))
    text = text.encode("cp1252", "ignore").decode("cp1252")
    return escape(text)


def _clip(text: str, length: int) -> str:
    text = re.sub(r"\s+", " ", text or "").strip()
    return text if len(text) <= length else text[: length - 1] + "…"


def _preferred_size(sizes: list[dict[str, Any]]) -> dict[str, Any] | None:
    """The headline size: the bottom-up estimate where one exists.

    §4.3.4 asks for the bottom-up estimate specifically. The procurement figure
    is a floor built from public contracts only, so it belongs beside it rather
    than instead of it — except where no bottom-up estimate exists at all, which
    is exactly the public-sector case where the procurement figure is the better
    evidence anyway.
    """
    for size in sizes:
        if size["method"] == "bottom_up_adoption":
            return size
    return sizes[0] if sizes else None


def brief_for_topic(db: Database, topic_id: str) -> dict[str, Any] | None:
    """Stored brief metadata, with staleness against the topic's version."""
    row = db.query_one("SELECT * FROM topic_briefs WHERE opportunity_id = ?", (topic_id,))
    if row is None:
        return None
    topic = db.query_one("SELECT version FROM opportunity_spaces WHERE id = ?", (topic_id,))
    # A brief goes stale two ways, and only one of them was checked. The topic
    # can move on — and the NARRATIVE can be rewritten underneath it, which is
    # the more likely of the two: someone reads the description, regenerates it,
    # and the PDF they emailed an hour ago now says something the radar does not.
    description = db.query_one(
        "SELECT generated_at FROM topic_descriptions WHERE opportunity_id = ?", (topic_id,)
    )
    description_moved = bool(
        description and row["description_at"] and description["generated_at"] != row["description_at"]
    )
    size = db.query_one(
        "SELECT MAX(computed_at) AS at FROM market_sizes WHERE opportunity_id = ?", (topic_id,)
    )
    sizing_moved = bool(size and size["at"] and row["market_size_at"] and size["at"] != row["market_size_at"])
    path = resolve_brief(row["path"])
    return {
        "topic_id": topic_id,
        "generated_at": row["generated_at"],
        "topic_version": row["topic_version"],
        "filename": row["filename"],
        "bytes": row["bytes"],
        "content_hash": row["content_hash"],
        "exists": path is not None,
        "stale": (bool(topic and topic["version"] != row["topic_version"])
                  or description_moved or sizing_moved or path is None),
        # Which of the three it is, so the warning can say something useful
        # rather than "this is old".
        "stale_reason": (
            "the topic has been refreshed since" if topic and topic["version"] != row["topic_version"]
            else "the written description has been regenerated since" if description_moved
            else "the market size has been recomputed since" if sizing_moved
            else "the PDF file is missing" if path is None else None
        ),
        # INCOMPLETE is not the same as STALE, and conflating them would hide
        # the more actionable of the two. A stale brief was correct when it was
        # made and has been overtaken. An incomplete brief never carried a
        # section that current briefs carry — here, the competitor analysis —
        # so no amount of waiting fixes it and the only remedy is to rebuild.
        "brief_schema": row["brief_schema"],
        "incomplete": row["brief_schema"] != BRIEF_SCHEMA,
        "missing_sections": ([] if row["brief_schema"] == BRIEF_SCHEMA
                             else ["Competitor analysis — what each competitor is doing in this "
                                   "space, and how Orange differentiates against each of them"]),
        "weight_set": row["weight_set"],
        "sizing_version": row["sizing_version"],
        "prompt_version": row["prompt_version"],
        "model_version": row["model_version"],
        "url": f"/api/topics/{topic_id}/brief.pdf",
    }


def brief_path(db: Database, topic_id: str) -> Path | None:
    row = db.query_one("SELECT path FROM topic_briefs WHERE opportunity_id = ?", (topic_id,))
    if row is None:
        return None
    return resolve_brief(row["path"])


def resolve_brief(recorded: str) -> Path | None:
    """The brief file for a recorded path, or None if it is not on this machine.

    The path column records where the brief was written, which is a machine the
    deployment has never seen: briefs are produced by the batch job and shipped
    as files, so on a server the recorded directory does not exist. The filename
    is stable, so fall back to the directory this process actually uses. Without
    this every brief 404s in Azure and the UI reports none were ever generated.
    """
    path = Path(recorded)
    if path.exists():
        return path
    fallback = brief_dir() / path.name
    return fallback if fallback.exists() else None


def brief_dir() -> Path:
    """Where briefs live for this process — see BriefBuilder.output_dir."""
    configured = os.getenv("RADAR_BRIEF_DIR")
    if configured:
        return Path(configured)
    # Anchored the way Config.db_path is, so this and BriefBuilder.output_dir
    # cannot disagree when the process runs from outside the repository root.
    from .config import PROJECT_ROOT
    return (PROJECT_ROOT / os.getenv("RADAR_DB_PATH", "data/radar.db")).parent / "briefs"
